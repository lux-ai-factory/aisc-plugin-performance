"""Integration tests for the classification plugin, driven by generated fixtures.

Each case folder under ``tests/files/`` (generated by ``tests/generate_files.py``)
carries the dataset, ONNX model, Data Shape and ConfigForm config used here.
"""

import json
from pathlib import Path

import pytest

from predictive_insights import ClassificationPerformancePlugin

FILES = Path(__file__).parent / "files"


def _load_case(case: str) -> dict:
    """Load a generated case folder."""
    folder = FILES / case
    return {
        "config": json.loads((folder / "config.json").read_text()),
        "datashape": json.loads((folder / "datashape.json").read_text()),
        "dataset": (folder / "dataset.csv").read_bytes(),
        "model": (folder / "model.onnx").read_bytes(),
    }


@pytest.fixture
def classification_plugin():
    """Create a classification plugin instance."""
    return ClassificationPerformancePlugin()


@pytest.fixture
def classification_case():
    """Generated classification fixtures."""
    return _load_case("classification")


@pytest.fixture
def prepared_plugin(classification_plugin, classification_case):
    """Plugin with test-dataset, model and datashape inputs attached."""
    plugin = classification_plugin
    plugin.set_input_content("test-dataset", classification_case["dataset"])
    plugin.set_input_content("model", classification_case["model"])
    plugin.set_input_content("datashape", json.dumps(classification_case["datashape"]).encode())
    return plugin


class TestClassificationPerformancePlugin:
    """Integration tests for ClassificationPerformancePlugin."""

    def test_plugin_name(self, classification_plugin):
        assert classification_plugin.plugin_name == "Classification Performance"

    def test_display_icon(self, classification_plugin):
        assert classification_plugin.display_icon == "category"

    def test_description(self, classification_plugin):
        description = classification_plugin.description
        assert description.startswith("Evaluates a trained ONNX classification model")
        assert "**Configuration:**" in description
        assert "- **Frequency**" in description
        assert "- **Window Size**" in description

    def test_metric_names(self, classification_plugin):
        metric_names = classification_plugin.metric_names()
        expected = [
            "Accuracy",
            "Precision",
            "Recall",
            "F1-Score",
            "Confusion-Matrix",
            "MCC",
            "SCE",
            "ECE",
            "MCE",
        ]
        assert metric_names == expected

    def test_set_input_providers(self, classification_plugin, classification_case):
        import pandas as pd
        from onnxruntime import InferenceSession

        classification_plugin.set_input_content("test-dataset", classification_case["dataset"])
        classification_plugin.set_input_content("model", classification_case["model"])

        assert classification_plugin._input_provider_instances.get("test-dataset") is not None
        assert classification_plugin._input_provider_instances.get("model") is not None
        assert isinstance(classification_plugin.get_input_data("test-dataset"), pd.DataFrame)
        assert isinstance(classification_plugin.get_input_data("model"), InferenceSession)

    def test_evaluate_missing_datashape_raises(self, classification_plugin, classification_case):
        classification_plugin.set_input_content("test-dataset", classification_case["dataset"])
        classification_plugin.set_input_content("model", classification_case["model"])

        with pytest.raises(ValueError, match="Data Shape input is required"):
            classification_plugin.evaluate({"frequency": "", "window_size": ""})

    def test_evaluate_without_windowing(self, prepared_plugin, classification_case):
        results = prepared_plugin.evaluate(classification_case["config"])

        assert isinstance(results, dict)
        # Check all expected metrics are present
        for metric in ["Accuracy", "Precision", "Recall", "F1-Score", "MCC"]:
            assert metric in results
            assert "score" in results[metric][0]
            assert len(results[metric]) == 1  # Single window

        # Check calibration metrics
        for metric in ["SCE", "ECE", "MCE"]:
            assert metric in results
            assert "score" in results[metric][0]

    def test_evaluate_metrics_valid_ranges(self, prepared_plugin, classification_case):
        results = prepared_plugin.evaluate(classification_case["config"])

        # Accuracy, Precision, Recall, F1 should be in [0, 1]
        for metric in ["Accuracy", "Precision", "Recall", "F1-Score"]:
            score = results[metric][0]["score"]
            assert 0.0 <= score <= 1.0, f"{metric} out of range: {score}"

        # MCC is normalized to [0, 1] in the plugin
        mcc = results["MCC"][0]["score"]
        assert 0.0 <= mcc <= 1.0, f"MCC out of range: {mcc}"

        # Calibration metrics should be non-negative
        for metric in ["SCE", "ECE", "MCE"]:
            score = results[metric][0]["score"]
            assert score >= 0.0, f"{metric} is negative: {score}"

    def test_evaluate_uses_datashape_roles(self, prepared_plugin):
        """The target/feature columns come from the generated data shape."""
        target, date, features = prepared_plugin._read_datashape()
        assert target == "target"
        assert date is None
        assert features == ["feat1", "feat2", "feat3", "feat4"]

    def test_get_metric_visualizations(self, prepared_plugin, classification_case):
        visualizations = prepared_plugin.get_metric_visualizations(classification_case["config"])

        assert len(visualizations) > 0
